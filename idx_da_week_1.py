# Create function to load all csv files in a folder

import os
import glob
import pandas as pd

def load_csv_files_from_folder(folder_path):
    """
    Loads all CSV files from the given folder into a list of Pandas DataFrames.
    Each DataFrame is paired with its filename.
    """
    if not os.path.isdir(folder_path):
        raise FileNotFoundError(f"Folder not found: {folder_path}")

    # Find all CSV files in the folder
    csv_files = glob.glob(os.path.join(folder_path, "*.csv"))

    if not csv_files:
        print("No CSV files found in the folder.")
        return []

    dataframes = []
    for file_path in csv_files:
        try:
            df = pd.read_csv(file_path)
            dataframes.append((os.path.basename(file_path), df))
            print(f"Loaded: {os.path.basename(file_path)} ({len(df)} rows)")
        except Exception as e:
            print(f"Error loading {file_path}: {e}")

    return dataframes

## Load Listing csv's
listings_csv_list = load_csv_files_from_folder("/content/drive/MyDrive/IDX Data Analyst/Listing")
listings_combined = pd.concat([df for __,df in listings_csv_list], ignore_index=True)
print("\nCombined DataFrame shape:", listings_combined.shape)

# Load Sold csv's

sold_csv_list = load_csv_files_from_folder("/content/drive/MyDrive/IDX Data Analyst/Sold")
sold_combined = pd.concat([df for __,df in listings_csv_list], ignore_index=True)
print("\nCombined DataFrame shape:", sold_combined.shape)

# Filter Listings by Residential Property Type
listings_residential = listings_combined[listings_combined['PropertyType'] == 'Residential']
print("\nListings Combined DataFrame shape:", listings_combined.shape)
print("\nFiltered Listings DataFrame shape:", listings_residential.shape)
#listings_residential.head(10)

# Filter Sold by Residential Property Type
sold_residential = sold_combined[sold_combined['PropertyType'] == 'Residential']
print("\nSold Combined DataFrame shape:", sold_combined.shape)
print("\nFiltered Sold DataFrame shape:", sold_residential.shape)
#sold_residential.head(10)

# Creating new csv files
listings_residential.to_csv('listings_residential.csv', index=False)
sold_residential.to_csv('sold_residential.csv', index=False)