# Helper function to plot filtered data to focus/zoom in on the main distribution
def plot_hist_zoom(ax, series, title, xlabel, bins=30, zoom_percentiles=(0.01, 0.99)):
    clean_series = series.dropna()
    if not clean_series.empty:
        # Determine zoom boundaries based on the specified percentiles
        lower_lim = clean_series.quantile(zoom_percentiles[0])
        upper_lim = clean_series.quantile(zoom_percentiles[1])

        # Filter data to only include values within this zoom range
        zoomed_data = clean_series[(clean_series >= lower_lim) & (clean_series <= upper_lim)]

        ax.hist(zoomed_data, bins=bins, color='skyblue', edgecolor='black', alpha=0.7)
        ax.set_xlim(lower_lim, upper_lim)

    ax.set_title(title)
    ax.set_xlabel(xlabel)
    ax.set_ylabel('Frequency')
    ax.grid(True, linestyle='--', alpha=0.5)

# Apply the zoomed plotting on all subplots
