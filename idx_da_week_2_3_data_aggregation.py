# Helper function to plot a clean horizontal boxplot for a column
def plot_box_zoom(ax, series, title, xlabel, zoom_percentiles=(0.01, 0.99)):
    clean_series = series.dropna()
    if not clean_series.empty:
        # Determine boundaries to exclude extreme tail outliers if desired, or plot the zoomed range
        lower_lim = clean_series.quantile(zoom_percentiles[0])
        upper_lim = clean_series.quantile(zoom_percentiles[1])

        zoomed_data = clean_series[(clean_series >= lower_lim) & (clean_series <= upper_lim)]

        ax.boxplot(zoomed_data, vert=False, patch_artist=True,
                   boxprops=dict(facecolor='skyblue', color='black'),
                   medianprops=dict(color='red', linewidth=1.5))
        ax.set_xlim(lower_lim, upper_lim)

    ax.set_title(title)
    ax.set_xlabel(xlabel)
    ax.set_yticks([]) # Hide the y-axis ticks as there is only one box group
    ax.grid(True, linestyle='--', alpha=0.5)

