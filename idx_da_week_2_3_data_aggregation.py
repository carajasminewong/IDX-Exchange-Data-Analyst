# returns a tuple of (low outliers, high outliers)
def count_outliers(df, col):
    q1 = df[col].quantile(0.25)
    q3 = df[col].quantile(0.75)
    iqr = q3 - q1
    lower_bound = q1 - 1.5 * iqr
    upper_bound = q3 + 1.5 * iqr
    lower_outliers = df[df[col] < lower_bound]
    upper_outliers = df[df[col] > upper_bound]
    return lower_outliers.shape[0], upper_outliers.shape[0]
print(count_outliers(sold, 'ClosePrice'))

