import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

# Load data files
listings = pd.read_csv("/content/drive/MyDrive/IDX Data Analyst/Datasets/listings_residential_with_rates.csv")
sold = pd.read_csv("/content/drive/MyDrive/IDX Data Analyst/Datasets/sold_residential_with_rates.csv")

print(f"Original Dimensions: {sold.shape}")

# save cleaned files in a copy
sold_cleaned = sold.copy()

# Task 1: convert dates to Datetime
date_cols = ['CloseDate', 'PurchaseContractDate', 'ListingContractDate', 'ContractStatusChangeDate']
for col in date_cols:
    sold_cleaned[col] = pd.to_datetime(sold_cleaned[col])

# find columns with high proportion of missing values
sold_columns = list(sold.columns)
sold_columns_types = list(sold.dtypes)
sold_missing_count = [sold[col].isnull().sum() for col in sold_columns]
sold_missing_prop = [sold[col].isnull().mean() for col in sold_columns]
sold_missing = pd.DataFrame({
    'Column Name': sold_columns,
    'Data Type': sold_columns_types,
    'Missing Count': sold_missing_count,
    'Missing Proportion': sold_missing_prop
})
# Filter directly using boolean indexing to prevent creating NaN rows
sold_missing_many = sold_missing[sold_missing['Missing Proportion'] > 0.9].sort_values('Missing Proportion', ascending=False)
sold_missing_many

# drop high missing columns
drop_cols = sold_missing_many['Column Name'].to_list()
sold_cleaned.drop(columns=drop_cols, inplace=True)

print(f"Dimensions of new dataset: {sold_cleaned.shape}")

# inspect the distribution of ClosePrice in the original 'sold' dataset
print(f"Total rows in original 'sold': {len(sold)}")
print(f"Null/NaN ClosePrice values: {sold['ClosePrice'].isnull().sum()}")
print(f"ClosePrice <= 0 (excluding NaNs): {len(sold[sold['ClosePrice'] <= 0])}")
print(f"ClosePrice > 0: {len(sold[sold['ClosePrice'] > 0])}")

"""Since there are a large number of Null/NaN Close Prices, I will flag these"""

sold_cleaned['Invalid ClosePrice'] = (sold['ClosePrice'].isnull()) | (sold['ClosePrice'] <= 0)
sold_cleaned['Invalid ClosePrice'].value_counts()

# repeat for Living Area <= 0, negative bedrooms/bathrooms, Days on market < 0
sold_cleaned['Invalid Living Area'] = (sold['LivingArea'] <= 0) | (sold['LivingArea'].isnull())
print(sold_cleaned['Invalid Living Area'].value_counts())
print("\n")

sold_cleaned['Invalid Bedrooms'] = (sold['BedroomsTotal'] < 0) | (sold['BedroomsTotal'].isnull())
print(sold_cleaned['Invalid Bedrooms'].value_counts())
print("\n")


sold_cleaned['Invalid Bathrooms'] = (sold['BathroomsTotalInteger'] < 0) | (sold['BathroomsTotalInteger'].isnull())
print(sold_cleaned['Invalid Bathrooms'].value_counts())
print("\n")

sold_cleaned['Invalid Days on Market'] = (sold['DaysOnMarket'] < 0) | (sold['DaysOnMarket'].isnull())
print(sold_cleaned['Invalid Days on Market'].value_counts())

"""Data Consistency Checks"""

sold_cleaned['listing_after_close_flag'] = sold_cleaned['ListingContractDate'] > sold_cleaned['CloseDate']
print(sold_cleaned['listing_after_close_flag'].value_counts())
print("\n")

sold_cleaned['purchase_after_close_flag'] = sold_cleaned['PurchaseContractDate'] > sold_cleaned['CloseDate']
print(sold_cleaned['purchase_after_close_flag'].value_counts())
print("\n")

sold_cleaned['negative_timeline_flag'] = sold_cleaned['DaysOnMarket'] < 0
print(sold_cleaned['negative_timeline_flag'].value_counts())
print("\n")

print(f"New Dimensions: {sold.shape}")

"""Geographic Data Check"""

# Filter Data to be CA
sold_cleaned = sold_cleaned[sold_cleaned['StateOrProvince'] == 'CA']
print(f"Dimensions of new dataset: {sold_cleaned.shape}")

# Invalid CA Latitude summary
null_lat_ca = sold_cleaned['Latitude'].isnull().sum()
out_of_bounds_ca = ((sold_cleaned['Latitude'] < 32.537) | (sold_cleaned['Latitude'] > 42.010)) & sold_cleaned['Latitude'].notnull()

print(f"Total flagged invalid CA Latitudes: {sold_cleaned['Invalid CA Latitude'].sum()}")
print(f"- Missing (NaN) Latitudes in CA: {null_lat_ca}")
print(f"- Out-of-bounds Latitudes in CA (excluding NaNs): {out_of_bounds_ca.sum()}")

# Flag invalid latitude/longitude for CA

# Latitude range for CA: ~32.537 to 42.010
sold_cleaned['Invalid CA Latitude'] = (sold_cleaned['Latitude'] < 32.537) | (sold_cleaned['Latitude'] > 42.010) | \
      (sold_cleaned['Latitude'].isnull())
print(sold_cleaned['Invalid CA Latitude'].value_counts())
print("\n")

# Longitude range for CA: -124.415 to -114.132
sold_cleaned['Invalid CA Longitude'] = (sold_cleaned['Longitude'] > -114.132) | (sold_cleaned['Longitude'] < -124.415) | \
 (sold_cleaned['Longitude'].isnull())
print(sold_cleaned['Invalid CA Longitude'].value_counts())
print("\n")

